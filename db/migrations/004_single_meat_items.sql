-- 004: ເມນູດຽວຕໍ່ໝວດ ແລ້ວເລືອກຊະນິດຊີ້ນໃນຕົວເລືອກ (ໝູ່ / ໄກ່ / ຊີ້ນງົວ / ເປັດ)
-- ບໍ່ລຶບເມນູເກົ່າ (ອາດມີບິນເກົ່າອ້າງອີງ) ແຕ່ປິດການໃຊ້ງານ (is_active = false)
-- ປອດໄພຮັນຊ້ຳໄດ້

-- ເຂົ້າປຽກ: ໃຊ້ແຖວ "ເຂົ້າປຽກໝູ່" ເປັນເມນູດຽວ
UPDATE menu_items
SET name = 'ເຂົ້າປຽກ', price_lak = 35000, is_active = true
WHERE id = '00000000-0000-0000-0000-000000001001';

-- ເຂົ້າປຽກໄກ່ ແລະ ເຂົ້າປຽກປາ: ປິດ
UPDATE menu_items SET is_active = false
WHERE id IN ('00000000-0000-0000-0000-000000001002', '00000000-0000-0000-0000-000000001003');

-- ເຝີ: ໃຊ້ແຖວ "ເຝີງົວ" ເປັນເມນູດຽວ
UPDATE menu_items
SET name = 'ເຝີ', price_lak = 40000, is_active = true
WHERE id = '00000000-0000-0000-0000-000000001004';

-- ລ້ອນ: ເກັບໄວ້ເປັນເມນູດຽວ
UPDATE menu_items
SET name = 'ລ້ອນ', price_lak = 40000, is_active = true
WHERE id = '00000000-0000-0000-0000-000000001005';

-- ໝີ່: ໃຊ້ແຖວ "ໝີ່ເປັດ" ເປັນເມນູດຽວ (ຄົງ signature ໄວ້)
UPDATE menu_items
SET name = 'ໝີ່', price_lak = 40000, is_active = true
WHERE id = '00000000-0000-0000-0000-000000001006';

-- ຮັບປະກັນວ່າທຸກເມນູອາຫານທີ່ເຫຼືອ ມີກຸ່ມ "ເລືອກຊະນິດຊີ້ນ" ແລະ ຕົວເລືອກຄົບ
-- (ເມນູທີ່ປິດແລ້ວຈະບໍ່ສະແດງໃນໜ້າຂາຍ)
